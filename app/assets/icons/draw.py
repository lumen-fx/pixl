SCALE = 4

def png(path, rows):
    rows = [r for r in rows for _ in range(SCALE)]
    rows = ["".join(c * SCALE for c in r) for r in rows]
    h = len(rows); w = len(rows[0])
    raw = b""
    for r in rows:
        raw += b"\x00"
        for c in r:
            if c == "#":
                raw += b"\xff\xff\xff\xff"
            elif c == "o":
                raw += b"\xff\xff\xff" + bytes((110,))
            else:
                raw += b"\x00\x00\x00\x00"
    def ch(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
    data = b"\x89PNG\r\n\x1a\n" + ch(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)) + ch(b"IDAT", zlib.compress(raw, 9)) + ch(b"IEND", b"")
    open(path, "wb").write(data)

def parse(art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), rows
    return rows

if __name__ == "__main__":
    out = os.path.dirname(os.path.abspath(__file__))
    for name, art in ICONS.items():
        png(os.path.join(out, name + ".png"), parse(art))
